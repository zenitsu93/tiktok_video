import { DeleteObjectCommand, GetObjectCommand, HeadObjectCommand, PutObjectCommand, S3Client } from "@aws-sdk/client-s3";
import { getSignedUrl } from "@aws-sdk/s3-request-presigner";
import { createReadStream, createWriteStream, existsSync } from "node:fs";
import { mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { dirname, join, resolve, sep } from "node:path";
import { Readable } from "node:stream";
import { pipeline } from "node:stream/promises";
import { env } from "./env";

/**
 * Files live either on a private disk volume (one server) or in a private
 * S3-compatible bucket such as Cloudflare R2 (app and worker on different hosts).
 * Keys are generated by the app, never taken from a request.
 */
export interface Storage {
  put(key: string, body: Buffer, mime: string): Promise<void>;
  read(key: string): Promise<Buffer>;
  /** Copies an object to a local file (the renderer needs files on disk). */
  download(key: string, path: string): Promise<void>;
  exists(key: string): Promise<boolean>;
  size(key: string): Promise<number>;
  stream(key: string, range?: { start: number; end: number }): Promise<Readable>;
  /** A short-lived direct URL when the backend has one (S3), else null. */
  directUrl(key: string, seconds: number, filename?: string): Promise<string | null>;
  /** Deletes a file; a missing one is not an error. */
  remove(key: string): Promise<void>;
}

const KEY = /^[a-z0-9][a-z0-9/_.-]{0,200}$/;
function checkKey(key: string) {
  if (!KEY.test(key) || key.includes("..")) throw new Error(`invalid storage key: ${key}`);
}

/** The web app and the worker run from different folders; a relative STORAGE_DIR starts at the repository root for both. */
function workspaceRoot(): string {
  for (let dir = process.cwd(); ; dir = dirname(dir)) {
    if (existsSync(join(dir, "pnpm-workspace.yaml"))) return dir;
    if (dirname(dir) === dir) return process.cwd();
  }
}

class LocalStorage implements Storage {
  private root: string;
  constructor(dir: string) {
    this.root = resolve(workspaceRoot(), dir);
  }
  private path(key: string) {
    checkKey(key);
    const p = resolve(join(this.root, key));
    if (!p.startsWith(this.root + sep)) throw new Error("storage path escape");
    return p;
  }
  async put(key: string, body: Buffer) {
    const p = this.path(key);
    await mkdir(dirname(p), { recursive: true });
    await writeFile(p, body);
  }
  read(key: string) {
    return readFile(this.path(key));
  }
  async download(key: string, path: string) {
    await mkdir(dirname(path), { recursive: true });
    await pipeline(createReadStream(this.path(key)), createWriteStream(path));
  }
  async exists(key: string) {
    return stat(this.path(key)).then(
      () => true,
      () => false,
    );
  }
  async size(key: string) {
    return (await stat(this.path(key))).size;
  }
  async stream(key: string, range?: { start: number; end: number }) {
    return createReadStream(this.path(key), range);
  }
  async directUrl() {
    return null;
  }
  async remove(key: string) {
    await rm(this.path(key), { force: true });
  }
}

class S3Storage implements Storage {
  private s3: S3Client;
  private bucket: string;
  constructor() {
    const e = env();
    this.bucket = e.S3_BUCKET!;
    this.s3 = new S3Client({
      region: e.S3_REGION,
      endpoint: e.S3_ENDPOINT,
      credentials: { accessKeyId: e.S3_ACCESS_KEY_ID!, secretAccessKey: e.S3_SECRET_ACCESS_KEY! },
    });
  }
  async put(key: string, body: Buffer, mime: string) {
    checkKey(key);
    await this.s3.send(new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: body, ContentType: mime }));
  }
  async read(key: string) {
    const r = await this.s3.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
    return Buffer.from(await r.Body!.transformToByteArray());
  }
  async download(key: string, path: string) {
    await mkdir(dirname(path), { recursive: true });
    const r = await this.s3.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
    await pipeline(r.Body as Readable, createWriteStream(path));
  }
  async exists(key: string) {
    return this.s3.send(new HeadObjectCommand({ Bucket: this.bucket, Key: key })).then(
      () => true,
      () => false,
    );
  }
  async size(key: string) {
    const h = await this.s3.send(new HeadObjectCommand({ Bucket: this.bucket, Key: key }));
    return h.ContentLength ?? 0;
  }
  async stream(key: string, range?: { start: number; end: number }) {
    const r = await this.s3.send(
      new GetObjectCommand({ Bucket: this.bucket, Key: key, Range: range ? `bytes=${range.start}-${range.end}` : undefined }),
    );
    return r.Body as Readable;
  }
  async remove(key: string) {
    checkKey(key);
    await this.s3.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }
  async directUrl(key: string, seconds: number, filename?: string) {
    checkKey(key);
    return getSignedUrl(
      this.s3,
      new GetObjectCommand({
        Bucket: this.bucket,
        Key: key,
        ResponseContentDisposition: filename ? `attachment; filename="${filename.replace(/[^\w.-]/g, "_")}"` : undefined,
      }),
      { expiresIn: seconds },
    );
  }
}

let cached: Storage | undefined;
export function storage(): Storage {
  cached ??= env().STORAGE_DRIVER === "s3" ? new S3Storage() : new LocalStorage(env().STORAGE_DIR);
  return cached;
}
